// Rewrites packages/core/src/updates/ranking-history.ts from Google's Search
// Status Dashboard: every incident on the Ranking history page, with the start
// and end times from its incident page. Google's incidents.json feed keeps only
// the latest few, so this snapshot is what lets older windows find their
// updates. Run it after Google posts a new update:
//
//   node scripts/refresh-google-updates.mjs
import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

const ORIGIN = 'https://status.search.google.com'
const HISTORY = `${ORIGIN}/products/rGHU1u87FJnkP6W2GwMi/history`
const OUTPUT = resolve(
  import.meta.dirname,
  '../packages/core/src/updates/ranking-history.ts',
)

async function page(url) {
  const response = await fetch(url, { signal: AbortSignal.timeout(15_000) })
  if (!response.ok) throw new Error(`${url} answered ${response.status}`)
  return response.text()
}

const decode = (text) =>
  text
    .replace(/<[^>]+>/g, ' ')
    .replace(/&amp;/g, '&')
    .replace(/&#39;/g, "'")
    .replace(/&quot;/g, '"')
    .replace(/\s+/g, ' ')
    .trim()

// A US/Pacific wall-clock time as an ISO time in UTC.
function pacificToUtc(local) {
  const [date, time] = local.split(' ')
  const guess = new Date(`${date}T${time}:00Z`)
  const parts = Object.fromEntries(
    new Intl.DateTimeFormat('en-US', {
      timeZone: 'America/Los_Angeles',
      hourCycle: 'h23',
      year: 'numeric',
      month: '2-digit',
      day: '2-digit',
      hour: '2-digit',
      minute: '2-digit',
    })
      .formatToParts(guess)
      .map((part) => [part.type, part.value]),
  )
  const shown = Date.UTC(
    Number(parts.year),
    Number(parts.month) - 1,
    Number(parts.day),
    Number(parts.hour),
    Number(parts.minute),
  )
  const utc = new Date(guess.getTime() + (guess.getTime() - shown))
  return `${utc.toISOString().slice(0, 19)}+00:00`
}

const history = await page(HISTORY)
const ids = [
  ...new Set(
    [...history.matchAll(/incidents\/([A-Za-z0-9]+)/g)].map((m) => m[1]),
  ),
]
if (ids.length < 40) throw new Error(`Only ${ids.length} incidents found.`)

const incidents = []
for (const id of ids) {
  const html = await page(`${ORIGIN}/incidents/${id}`)
  const text = decode(html)
  const name = text.match(
    /Incident affecting Ranking (.+?) Incident began/,
  )?.[1]
  const began = text.match(/Incident began at (\d{4}-\d\d-\d\d \d\d:\d\d)/)?.[1]
  const ended = text.match(/and ended at (\d{4}-\d\d-\d\d \d\d:\d\d)/)?.[1]
  if (!began || !name) throw new Error(`Could not read incident ${id}.`)
  incidents.push({
    id,
    begin: pacificToUtc(began),
    ...(ended ? { end: pacificToUtc(ended) } : {}),
    external_desc: name.trim(),
  })
}

// Check the parsing against the live feed, which has exact times.
const feed = await (await fetch(`${ORIGIN}/incidents.json`)).json()
for (const live of feed) {
  const mine = incidents.find((incident) => incident.id === live.id)
  if (!mine) continue
  const same = (a, b) => (a && b ? Date.parse(a) === Date.parse(b) : a === b)
  if (!same(mine.begin, live.begin) || !same(mine.end, live.end)) {
    throw new Error(`Times for ${live.id} do not match the feed.`)
  }
}

incidents.sort((a, b) => (a.begin < b.begin ? 1 : a.begin > b.begin ? -1 : 0))
const rows = incidents
  .map((incident) => `  ${JSON.stringify(incident)},`)
  .join('\n')
writeFileSync(
  OUTPUT,
  `// Generated by scripts/refresh-google-updates.mjs from Google's Search Status
// Dashboard Ranking history. Do not edit by hand.

export const RANKING_HISTORY_CHECKED = '${new Date().toISOString().slice(0, 10)}'

export const RANKING_HISTORY: ReadonlyArray<{
  id: string
  begin: string
  end?: string
  external_desc: string
}> = [
${rows}
]
`,
)
execFileSync('pnpm', ['exec', 'biome', 'format', '--write', OUTPUT])
console.log(`Wrote ${incidents.length} ranking updates to ${OUTPUT}`)
